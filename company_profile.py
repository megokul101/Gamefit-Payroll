"""Company identity, constrained logo uploads and immutable document branding."""
import base64,copy,re,struct
DEFAULT_COMPANY={'name':'Gamefit Lively','legalName':'','address':'','email':'','phone':'','website':'','taxId':'','registrationNumber':'','logo':'','payslipPrefix':'GF','documentFooter':'Generated by the company payroll administrator.','currency':'INR'}
def company_for(state):return {**DEFAULT_COMPANY,**state.get('company',{})}
def validate_company(value):
 if not isinstance(value,dict):raise ValueError('Invalid company profile')
 out=dict(DEFAULT_COMPANY)
 limits={'name':100,'legalName':160,'address':600,'email':120,'phone':50,'website':180,'taxId':60,'registrationNumber':60,'payslipPrefix':10,'documentFooter':300}
 for key,limit in limits.items():
  v=value.get(key,out[key])
  if not isinstance(v,str) or len(v)>limit:raise ValueError('Invalid company field: '+key)
  out[key]=v.strip()
 if not out['name']:raise ValueError('Company name is required')
 if not re.fullmatch(r'[A-Z0-9-]{1,10}',out['payslipPrefix']):raise ValueError('Payslip prefix must use 1-10 uppercase letters, digits or hyphens')
 logo=value.get('logo','')
 if not isinstance(logo,str) or len(logo)>350000:raise ValueError('Logo must be a small PNG image')
 if logo:
  prefix='data:image/png;base64,'
  if not logo.startswith(prefix):raise ValueError('Logo must be PNG')
  try:raw=base64.b64decode(logo[len(prefix):],validate=True)
  except Exception:raise ValueError('Invalid logo data')
  if len(raw)>256000 or len(raw)<33 or raw[:8]!=b'\x89PNG\r\n\x1a\n' or raw[12:16]!=b'IHDR':raise ValueError('Invalid PNG logo')
  w,h=struct.unpack('>II',raw[16:24])
  if not (0<w<=1024 and 0<h<=1024):raise ValueError('Logo dimensions must not exceed 1024 pixels')
 out['logo']=logo;return out
